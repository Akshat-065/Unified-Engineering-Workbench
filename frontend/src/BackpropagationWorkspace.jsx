import { useEffect, useState } from 'react';
import { Activity, CircleAlert, RefreshCw } from 'lucide-react';

const API = '/api/ml/backprop';
const names = ['w', 'b', 'v', 'c'];

function LossChart({ history }) {
  const width = 760, height = 260, pad = { left: 58, right: 20, top: 20, bottom: 42 };
  if (!history?.length) return <div className="ml-chart-empty">Loss history is unavailable.</div>;
  const values = history.map((point) => point.loss);
  const low = Math.min(...values), high = Math.max(...values);
  const x = (i) => pad.left + i * (width - pad.left - pad.right) / Math.max(1, history.length - 1);
  const y = (value) => height - pad.bottom - (value - low) * (height - pad.top - pad.bottom) / (high - low || 1);
  const path = history.map((point, i) => `${i ? 'L' : 'M'} ${x(i)} ${y(point.loss)}`).join(' ');
  return <div className="ml-chart-wrap"><svg className="ml-loss-chart" viewBox={`0 0 ${width} ${height}`} role="img" aria-label="Loss versus training step chart">
    <line x1={pad.left} y1={pad.top} x2={pad.left} y2={height - pad.bottom} className="chart-axis" />
    <line x1={pad.left} y1={height - pad.bottom} x2={width - pad.right} y2={height - pad.bottom} className="chart-axis" />
    <text x="15" y="24" className="chart-label">Loss J</text><text x={width / 2} y={height - 8} textAnchor="middle" className="chart-label">Training step</text>
    <text x={pad.left - 8} y={pad.top + 4} textAnchor="end" className="chart-tick">{high.toFixed(3)}</text>
    <text x={pad.left - 8} y={height - pad.bottom} textAnchor="end" className="chart-tick">{low.toFixed(3)}</text>
    <text x={pad.left} y={height - pad.bottom + 20} className="chart-tick">0</text>
    <text x={width - pad.right} y={height - pad.bottom + 20} textAnchor="end" className="chart-tick">{history.at(-1).step}</text>
    <path d={path} className="loss-line" />
  </svg></div>;
}

export default function BackpropagationWorkspace({ backendAvailable }) {
  const [result, setResult] = useState(null);
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);
  async function refresh() {
    setLoading(true); setError('');
    try {
      const response = await fetch(API);
      const payload = await response.json();
      if (!response.ok) throw new Error(payload.error || `HTTP ${response.status}`);
      setResult(payload);
    } catch (e) { setError(e instanceof Error ? e.message : 'Unable to load C++ model results'); }
    finally { setLoading(false); }
  }
  useEffect(() => { if (backendAvailable) refresh(); }, [backendAvailable]);
  return <div className="ml-workspace">
    <section className="welcome"><div><div className="eyebrow"><span className="eyebrow-line" /> MACHINE LEARNING <span className="eyebrow-line" /></div><h1>Backpropagation <em>lab.</em></h1><p>Single-sample tanh network with C++ gradients, finite-difference check, and gradient descent.</p></div><button className="refresh-button" onClick={refresh} disabled={loading} aria-label="Refresh calculation"><RefreshCw size={17} className={loading ? 'spinning' : ''} /></button></section>
    <div className="simulation-notice"><Activity size={16} /> Model computation and training history are generated by the C++ backend.</div>
    {error && <div className="ml-error"><CircleAlert size={17} />{error}</div>}
    {!backendAvailable && <div className="ml-error"><CircleAlert size={17} />Backend unavailable. Start workbench_server to retrieve the C++ results.</div>}
    {result && <>
      <section className="ml-metric-grid">
        <article className="ml-metric"><span>INITIAL LOSS</span><strong>{result.initial_loss.toFixed(8)}</strong><small>Step 0 · η = {result.learning_rate}</small></article>
        <article className="ml-metric"><span>LOSS AFTER FIRST UPDATE</span><strong>{result.loss_after_first_update.toFixed(8)}</strong><small>Simultaneous parameter update</small></article>
        <article className="ml-metric"><span>LOSS AFTER TRAINING</span><strong>{result.final_loss.toExponential(4)}</strong><small>100 additional updates · step 101</small></article>
        <article className="ml-metric"><span>FINITE-DIFFERENCE CHECK</span><strong>{Math.max(...Object.values(result.gradient_check.absolute_error)).toExponential(2)}</strong><small>Max absolute gradient error</small></article>
      </section>
      <section className="panel ml-panel"><div className="panel-heading"><div><div className="eyebrow muted">OPTIMIZATION</div><h2>Loss versus training step</h2></div><span className="live-badge"><i /> C++ DATA</span></div><LossChart history={result.loss_history} /></section>
      <div className="ml-grid-two">
        <section className="panel ml-panel"><div className="panel-heading"><div><div className="eyebrow muted">FORWARD PASS</div><h2>Initial state</h2></div></div><div className="ml-equations"><div><span>Input x / target y</span><b>{result.input} / {result.target}</b></div><div><span>Hidden activation h = tanh(wx + b)</span><b>{result.hidden_activation.toFixed(10)}</b></div><div><span>Prediction ŷ = vh + c</span><b>{result.predicted_output.toFixed(10)}</b></div><div><span>Initial loss J</span><b>{result.initial_loss.toFixed(10)}</b></div></div></section>
        <section className="panel ml-panel"><div className="panel-heading"><div><div className="eyebrow muted">CHAIN RULE + CHECK</div><h2>Parameter gradients</h2></div></div><div className="ml-table-scroll"><table className="ml-gradient-table"><thead><tr><th>Parameter</th><th>Analytical</th><th>Central diff.</th><th>Abs. error</th></tr></thead><tbody>{names.map((name) => <tr key={name}><td>{name}</td><td>{result.gradient_check.analytical[name].toFixed(9)}</td><td>{result.gradient_check.numerical[name].toFixed(9)}</td><td>{result.gradient_check.absolute_error[name].toExponential(2)}</td></tr>)}</tbody></table></div></section>
      </div>
      <footer><span>TRAINING HISTORY IS GENERATED BY WORKBENCH_ML</span><span>CSV: results/backpropagation_loss.csv</span></footer>
    </>}
  </div>;
}
